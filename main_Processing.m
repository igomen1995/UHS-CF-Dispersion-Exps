%% main_Processing.m
% Author: Ianna Gomez Mendez
%
% PURPOSE
%   Estimate transport and dispersion parameters from experimentally
%   measured breakthrough curves (BTCs).
%
%   The workflow fits analytical solutions of the one-dimensional
%   Advection–Dispersion Equation (ADE) to processed breakthrough-curve
%   data and determines:
%
%       - Longitudinal dispersion coefficient (KL)
%       - Time delay (dt)
%       - Dispersivity (alpha)
%       - Tortuosity (tau)
%
%   Multiple fitting methodologies are evaluated and compared in order
%   to identify the most robust transport-parameter estimates.
%
% -------------------------------------------------------------------------
% INPUTS
% -------------------------------------------------------------------------
%
% Configuration:
%
%       inputExpConfig.xlsx
%
% Experimental metadata:
%
%       inputExp.xlsx
%
% Processed breakthrough-curve database generated by:
%
%       main_DataExtract.m
%
%           expProcData.mat
%
% -------------------------------------------------------------------------
% TRANSPORT MODEL
% -------------------------------------------------------------------------
%
%   The breakthrough curves are fitted using analytical solutions of the
%   one-dimensional Advection–Dispersion Equation:
%
%       ∂C/∂t + u ∂C/∂x
%           =
%       KL ∂²C/∂x²
%
%   where:
%
%       C     Concentration
%       u     Interstitial velocity
%       KL    Longitudinal dispersion coefficient
%
% -------------------------------------------------------------------------
% FITTING OBJECTIVES
% -------------------------------------------------------------------------
%
%   Estimate:
%
%       KL
%       dt
%
%   for each core-flood experiment.
%
%   The parameter dt accounts for transport delays associated with:
%
%       - Tubing volume
%       - Instrument volume
%       - Dead volume external to the core
%
% -------------------------------------------------------------------------
% FITTING STRATEGIES
% -------------------------------------------------------------------------
%
%   Multiple fitting approaches are evaluated:
%
%       dt_free_wfit
%       dt_free_nwfit
%
%       dt_fixed_wfit_wdt_lim
%       dt_fixed_nwfit_wdt_lim
%
%       dt_fixed_wfit_nwdt_lim
%       dt_fixed_nwfit_nwdt_lim
%
%       dt_fixed_wfit_wdt_full
%       dt_fixed_nwfit_wdt_full
%
%       dt_fixed_wfit_nwdt_full
%       dt_fixed_nwfit_nwdt_full
%
%   where:
%
%       dt_free     = dt optimized during fitting
%       dt_fixed    = dt fixed from previous estimates
%
%       wfit        = weighted regression
%       nwfit       = unweighted regression
%
%       lim         = only breakthrough region fitted
%                    (typically 16–84 % concentration)
%
%       full        = entire breakthrough curve fitted
%
% -------------------------------------------------------------------------
% METHOD SELECTION
% -------------------------------------------------------------------------
%
%   Each fitting method is evaluated using:
%
%       RMSE
%       R²
%
%   The preferred fitting strategy is selected as the method that:
%
%       1. Produces valid parameter estimates
%       2. Maximizes average R²
%
%   The chosen method is stored as:
%
%       results.model
%
% -------------------------------------------------------------------------
% FITTED PARAMETERS
% -------------------------------------------------------------------------
%
%   For each experiment:
%
%       KL
%       dKL
%
%       dt
%       ddt
%
%       Pe
%
%       KL/D0
%
%       Model prediction
%
% -------------------------------------------------------------------------
% DISPERSIVITY ESTIMATION
% -------------------------------------------------------------------------
%
%   Longitudinal dispersivity is estimated from:
%
%       KL = D0 + alpha*u
%
%   or equivalent Peclet-number formulations.
%
%   Estimated parameters:
%
%       alpha
%       d_alpha
%
%   reported in:
%
%       SI units
%       centimeters
%
% -------------------------------------------------------------------------
% TORTUOSITY ESTIMATION
% -------------------------------------------------------------------------
%
%   When sufficient experiments exist for a fluid system,
%   simultaneous estimation of:
%
%       alpha
%       tau
%
%   is attempted using:
%
%       fit_dispersion_params_alpha_tau
%
%   Tortuosity estimation is only retained when:
%
%       tau > 0
%
%   and uncertainty remains physically reasonable.
%
% -------------------------------------------------------------------------
% DIMENSIONLESS NUMBERS
% -------------------------------------------------------------------------
%
%   Peclet numbers are calculated using:
%
%       Pe_D0 = uL/D0
%
%   and related transport formulations.
%
%   These parameters are used for:
%
%       - KL scaling
%       - Dispersivity fitting
%       - Transport-regime analysis
%
% -------------------------------------------------------------------------
% GENERATED FIGURES
% -------------------------------------------------------------------------
%
% 1. Experimental BTC vs fitted BTC
%
%       Ci vs Time
%
% 2. Dimensionless BTC comparison
%
%       CDi vs tD
%
% 3. Total-volume dimensionless BTC
%
%       CDi vs tDtotal
%
% 4. Grouped BTC fits
%
%       Same fluids
%       Same T
%       Same P
%       Multiple Q
%
% 5. KL versus interstitial velocity
%
%       KL vs u
%
%       Used for alpha estimation.
%
% 6. Dimensionless transport analysis
%
%       KL/D0 vs Pe
%
% -------------------------------------------------------------------------
% OUTPUT FILES
% -------------------------------------------------------------------------
%
% MATLAB databases:
%
%       expProcFullData.mat
%       alpha_results.mat
%
% Excel files:
%
%       fitting_results.xlsx
%       alpha_results.xlsx
%
% Figures:
%
%       *_fitting.png
%       *_fittingAll.png
%
%       *_dimless_fitting.png
%       *_dimlessTotal_fitting.png
%
%       KLvsVel_*.png
%       KLD0vsPe_all_*.png
%
% -------------------------------------------------------------------------
% OUTPUT TABLES
% -------------------------------------------------------------------------
%
% Best-fitting transport parameters:
%
%       KL
%       dKL
%
%       dt
%       ddt
%
%       R²
%       RMSE
%
%       D0
%
%       Pe
%
% Alpha-analysis table:
%
%       alpha
%       d_alpha
%
%       tau
%       d_tau
%
% -------------------------------------------------------------------------
% DEPENDENCIES
% -------------------------------------------------------------------------
%
% Data processing:
%
%       main_DataExtract.m
%
% Fitting functions:
%
%       fit_dispersion_dt_nlinfit
%       fit_dispersion_dtfixed_nlinfit
%
%       fit_dispersion_params_alpha
%       fit_dispersion_params_alpha_tau
%
% Utility functions:
%
%       buildRow_procResults
%
% -------------------------------------------------------------------------
% NOTES
% -------------------------------------------------------------------------
%
%   - Core-flood experiments are identified using:
%
%         Type == "CF"
%
%   - Weighted regressions use composition uncertainties propagated
%     from density-calibration uncertainty.
%
%   - Multiple fitting methodologies are intentionally compared to
%     evaluate robustness of KL estimation.
%
%   - Transport-property estimates generated in this workflow are the
%     final quantitative outputs of the experimental framework.
%
%   - Results are intended for dispersion analysis, transport-model
%     calibration, and publication-quality interpretation.

%% INPUT

addpath('functions/');

inputFileConfigName = 'inputExpConfig.xlsx';

inputFileConfig = readtable(inputFileConfigName);

filenameExp = inputFileConfig.inputFileName{:};
eosMethod = inputFileConfig.eosMethod{:};
diffMethod = inputFileConfig.diffMethod{:};
fitData = inputFileConfig.fitData{:};

pathImportAll = inputFileConfig.exportPath{:}; % Path for INPUT
pathExportAll = pathImportAll;
mkdir(pathImportAll); % Create directory for output

% validity limits (move to the INPUT section if the dt-fixed fitting also uses them)
KL_valid_min  = 0;     % cm2/min (exclusive)
KL_valid_max  = 100;   % cm2/min
dtD_valid_min = 0;     % dimensionless delay (pore volumes)
dtD_valid_max = 5;
min_exp_dtfixed = 0; 

beta_tau = 1.0;   % exponent of the dispersive term in KL = D0*(1/tau + C2*Pe^beta); 1 = linear

%% IMPORT variables

filedataExp = import_inputExp(filenameExp); % import input to a local variable

load(pathImportAll+"expProcData.mat")

%% dt groups: same fluids, T, P and setup (line configuration) -> same dtD
nExp = height(filedataExp);
setupVersion = strings(nExp,1);
for i = 1:nExp
    ep = expProcData.(filedataExp.Key(i)).exp_params;
    if ~ismember('setupVersion', ep.Properties.VariableNames)
        error("setupVersion missing in exp_params of %s", filedataExp.Key(i))
    end
    setupVersion(i) = string(ep.setupVersion);
end
dtGroupID = string(filedataExp.Fluid1) + "_" + string(filedataExp.Fluid2) + ...
            "_T" + string(filedataExp.T) + "_P" + string(filedataExp.P) + ...
            "_S" + setupVersion;

[gU,~,gIdx] = unique(dtGroupID, 'stable');
disp("dt groups (same fluids, T, P, setup):")
disp(table(gU, accumarray(gIdx,1), 'VariableNames', {'dtGroupID','nExp'}))

%% Fitting dispersion to find KL and dt short equation ADE
% dt free

% No need to correct BT curve due to extra volume before core, the
% fit_dispersion_dt corrects for that extra t

method_results = struct();

methods = {'dt_free_wfit', 'dt_free_nwfit', ...
    'dt_fixed_wdt_wfit_lim','dt_fixed_nwdt_wfit_lim', ...
    'dt_fixed_wdt_nwfit_lim', 'dt_fixed_nwdt_nwfit_lim', ...
    'dt_fixed_wdt_wfit_full','dt_fixed_nwdt_wfit_full', ...
    'dt_fixed_wdt_nwfit_full', 'dt_fixed_nwdt_nwfit_full'};

for m = 1:length(methods)
    method_results.(methods{m}) = table();
end

for i = 1:length(filedataExp.Key)
    if filedataExp.Type(i) == "CF"

        % data
        t_vals = expProcData.(filedataExp.Key(i)).BT.SecondsElapsed;
        
        switch fitData
            case "woEOS"
                C1_vals = expProcData.(filedataExp.Key(i)).BT.rho_norm;
                dC_vals = expProcData.(filedataExp.Key(i)).BT.drho_norm;
            otherwise
                C1_vals = expProcData.(filedataExp.Key(i)).BT.Ci/100;
                dC_vals = expProcData.(filedataExp.Key(i)).BT.dC/100;    
        end
        % experiment params (fixed for fitting)
        Ci = filedataExp.C1init(i)/100;
        Cj = filedataExp.C1j(i)/100;
        u = expProcData.(filedataExp.Key(i)).exp_params.u_SI; % from pump
        % u = expProcData.(filedataExp.Key(i)).exp_params.uavg_MFM_SI; % from MFM average
        L = expProcData.(filedataExp.Key(i)).exp_params.L_SI;

        % dt shift guess = Vlines total / Q 
        dt_guess = (filedataExp.Vlinesbefore(i)+filedataExp.Vlinesafter(i))*60/filedataExp.Q(i); % time in seconds
        % dt_guess = (filedataExp.Vlinesbefore(i)+filedataExp.Vlinesafter(i))*60/expProcData.(filedataExp.Key(i)).exp_params.Qavg_MFM_mlmin; % time in seconds
        p_guess = [1,dt_guess];

        % dt_free_w dt free weigthed
        % non linear fitting using [p_est,R,J,CovB,MSE,ErrorModelInfo] = nlinfit(t_trim, C_trim, C_function, p0, opts, 'Weights', w_trim);
        KL_out = fit_dispersion_dt_nlinfit(C1_vals,t_vals,u,Cj,Ci,L,p_guess,dC_vals); % weigthed with errors

        % exp params for table
        row = buildRow_procResults(filedataExp, expProcData, KL_out, i);
        row.dtGroupID = dtGroupID(i);
        row.n_dtGroup = NaN;          % dt not fixed for dt_free fits
        row.model = "dt_free_wfit";

        method_results.(row.model) = [method_results.dt_free_wfit; row];

        expProcData.(filedataExp.Key(i)).BT.C_fit_dt_free = 100*KL_out.C_fit;

        % dt_free_nw dt free non weigthed
        % non linear fitting using [p_est,R,J,CovB,MSE,ErrorModelInfo] = nlinfit(t_trim, C_trim, C_function, p0, opts, 'Weights', w_trim);
        KL_out = fit_dispersion_dt_nlinfit(C1_vals,t_vals,u,Cj,Ci,L,p_guess,ones(size(C1_vals))); %non weighted (error is 1, hence w = 1./(dC.^2) = 1)

        % exp params for table
        row = buildRow_procResults(filedataExp, expProcData, KL_out, i);
        row.dtGroupID = dtGroupID(i);
        row.n_dtGroup = NaN;          % dt not fixed for dt_free fits
        row.model = "dt_free_nwfit";

        method_results.(row.model) = [method_results.dt_free_nwfit; row];

        expProcData.(filedataExp.Key(i)).BT.C_nw_fit_dt_free = 100*KL_out.C_fit;

    end
end

%% Group delay per setup group and dt source, weighted by fit quality
% dtD = u*dt/L = external dead volume in pore volumes -> one value per setup
% group (same fluids, T, P, setupVersion) and per dt source:
%   wdt  <- dt_free_wfit fits of the group
%   nwdt <- dt_free_nwfit fits of the group
% Weight of each fit: w = 1/RMSE^2 (better fit -> more weight).

dt_sources = {'wdt',  'dt_free_wfit'; ...
              'nwdt', 'dt_free_nwfit'};
gList     = unique(dtGroupID, 'stable');
dt_groups = table();

for g = 1:numel(gList)
    keysG = string(filedataExp.Key(dtGroupID == gList(g)));
    rowG  = table(gList(g), numel(keysG), 'VariableNames', {'dtGroupID','nExpGroup'});

    for s = 1:size(dt_sources,1)
        tag = dt_sources{s,1};
        Ts  = method_results.(dt_sources{s,2});

        ok = ismember(Ts.Key, keysG) & ...
             isfinite(Ts.dtD) & Ts.dtD >= dtD_valid_min & Ts.dtD <= dtD_valid_max & ...
             isfinite(Ts.KL_cm2min) & Ts.KL_cm2min > KL_valid_min & Ts.KL_cm2min <= KL_valid_max & ...
             isfinite(Ts.R2) & isfinite(Ts.RMSE) & Ts.RMSE > 0;

        vals  = Ts.dtD(ok);
        dfit  = Ts.d_dtD(ok);
        nUsed = numel(vals);
        dtD_g = NaN;  d_dtD_g = NaN;

        if nUsed >= max(min_exp_dtfixed, 1)
            wn    = (1 ./ Ts.RMSE(ok).^2);  wn = wn / sum(wn);     % fit-quality weights
            dtD_g = sum(wn .* vals);
            if nUsed > 1
                scatter_g = sqrt(sum(wn .* (vals - dtD_g).^2) * nUsed/(nUsed-1));
            else
                scatter_g = 0;
            end
            d_dtD_g = sqrt(scatter_g^2 + sum(wn .* dfit, 'omitnan')^2);
        end

        rowG.(['nUsed_' tag])     = nUsed;
        rowG.(['dtD_group_' tag]) = dtD_g;
        rowG.(['d_dtD_group_' tag]) = d_dtD_g;
        rowG.(['Keys_' tag])      = strjoin(Ts.Key(ok), ";");
    end
    dt_groups = [dt_groups; rowG]; %#ok<AGROW>
end

disp("Setup-group delay per dt source (dtD weighted by fit quality, w = 1/RMSE^2):")
disp(dt_groups(:, {'dtGroupID','nExpGroup', ...
    'nUsed_wdt','dtD_group_wdt','d_dtD_group_wdt', ...
    'nUsed_nwdt','dtD_group_nwdt','d_dtD_group_nwdt'}))

%% Fitting dispersion to find KL with dt fixed PER SETUP GROUP (8 methods)

Cmin = 0.16;  Cmax = 0.84;
fit_types = {'wfit', 'nwfit'};
ranges    = {'lim', Cmin, Cmax; ...
             'full', 0,    1};

for i = 1:nExp
    if filedataExp.Type(i) ~= "CF", continue, end
    key  = filedataExp.Key(i);
    gRow = find(dt_groups.dtGroupID == dtGroupID(i), 1);
    if isempty(gRow), continue, end

    t_vals = expProcData.(key).BT.SecondsElapsed;
    switch fitData
        case "woEOS"
            C1_vals = expProcData.(key).BT.rho_norm;
            dC_vals = expProcData.(key).BT.drho_norm;
        otherwise
            C1_vals = expProcData.(key).BT.Ci/100;
            dC_vals = expProcData.(key).BT.dC/100;
    end
    Ci = filedataExp.C1init(i)/100;
    Cj = filedataExp.C1j(i)/100;
    u  = expProcData.(key).exp_params.u_SI;
    L  = expProcData.(key).exp_params.L_SI;

    for s = 1:size(dt_sources,1)
        tag  = dt_sources{s,1};
        Tsrc = method_results.(dt_sources{s,2});

        dtD_fixed   = dt_groups.(['dtD_group_' tag])(gRow);
        d_dtD_fixed = dt_groups.(['d_dtD_group_' tag])(gRow);
        if ~isfinite(dtD_fixed), continue, end         % no valid fits for this source
        dt_fixed = dtD_fixed*L/u;                      % same dtD, dt scales with 1/Q

        % KL initial guess: this key's own dt_free fit (by Key), else group median
        r0 = find(Tsrc.Key == key, 1);
        if ~isempty(r0) && isfinite(Tsrc.KL_SI(r0)) && Tsrc.KL_SI(r0) > 0
            p_guess = sqrt(Tsrc.KL_SI(r0));
        else
            inG = ismember(Tsrc.Key, string(filedataExp.Key(dtGroupID == dtGroupID(i))));
            p_guess = sqrt(median(Tsrc.KL_SI(inG), 'omitnan'));
        end

        for f = 1:numel(fit_types)
            if strcmp(fit_types{f}, 'wfit')
                w_vals = dC_vals;
            else
                w_vals = ones(size(C1_vals));
            end

            for rg = 1:size(ranges,1)
                mName = ['dt_fixed_' tag '_' fit_types{f} '_' ranges{rg,1}];

                KL_out = fit_dispersion_dtfixed_nlinfit(C1_vals, t_vals, u, Cj, Ci, L, ...
                    dt_fixed, p_guess, w_vals, ranges{rg,2}, ranges{rg,3});

                row = buildRow_procResults(filedataExp, expProcData, KL_out, i);
                row = setFixedDt(row, dtD_fixed, d_dtD_fixed, u, L);
                row.dtGroupID = dtGroupID(i);
                row.n_dtGroup = dt_groups.(['nUsed_' tag])(gRow);
                row.model     = string(mName);

                method_results.(mName) = [method_results.(mName); row];
                expProcData.(key).BT.(['C_fit_' mName]) = 100*KL_out.C_fit;
            end
        end
    end
end

%% Attach the group delays to every method table (saved with the results)
mList = fieldnames(method_results);
for m = 1:numel(mList)
    Tm = method_results.(mList{m});
    if isempty(Tm), continue, end
    [~, gi] = ismember(Tm.dtGroupID, dt_groups.dtGroupID);
    for s = 1:size(dt_sources,1)
        tag = dt_sources{s,1};
        dtD  = dt_groups.(['dtD_group_' tag])(gi);
        ddtD = dt_groups.(['d_dtD_group_' tag])(gi);
        Tm.(['dtD_group_' tag])      = dtD;
        Tm.(['d_dtD_group_' tag])    = ddtD;
        Tm.(['dt_group_min_' tag])   = dtD  .* Tm.L_SI ./ Tm.u_SI / 60;   % in this experiment's time
        Tm.(['d_dt_group_min_' tag]) = ddtD .* Tm.L_SI ./ Tm.u_SI / 60;
    end
    method_results.(mList{m}) = Tm;
end
expProcData.dt_groups = dt_groups;

%% Select the best valid method for EACH experiment (key)

if isfield(method_results,'best_per_key')
    method_results = rmfield(method_results,'best_per_key');
end

method_names = fieldnames(method_results);
% candidate_methods = method_names(startsWith(method_names,"dt_fixed"));
% candidate_methods = method_names(startsWith(method_names,"dt_fixed_nwdt_nwfit") & endsWith(method_names,"lim"));
candidate_methods = method_names;   % also allow dt_free methods

disp("Candidate methods:"); disp(candidate_methods)

nExp  = height(filedataExp);
nCand = numel(candidate_methods);
best_rows  = table();
best_score = nan(nExp,1);
cand_row   = nan(nExp,nCand);   % row of key i in method m (NaN = not valid)

% best method per key (KL validity)
for i = 1:nExp
    key = filedataExp.Key(i);
    best_row = [];

    for m = 1:nCand
        Tm = method_results.(candidate_methods{m});
        if isempty(Tm), continue, end

        r = find(Tm.Key == string(key), 1);
        if isempty(r), continue, end          % method not run for this key

        ok = isfinite(Tm.KL_cm2min(r)) && ...
             Tm.KL_cm2min(r) > KL_valid_min && Tm.KL_cm2min(r) <= KL_valid_max && ...
             isfinite(Tm.dKL_SI(r)) && ...
             isfinite(Tm.R2(r)) && isfinite(Tm.RMSE(r)) && Tm.RMSE(r) > 0;
        if ~ok, continue, end

        cand_row(i,m) = r;   % remember valid methods for the spread

        score = Tm.R2(r) / Tm.RMSE(r);
        if isnan(best_score(i)) || score > best_score(i)
            best_score(i) = score;
            best_row = Tm(r,:);
        end
    end

    if isempty(best_row)
        error("No valid fitting method found for %s", key)
    end
    best_rows = [best_rows; best_row]; %#ok<AGROW>
end
best_rows.best_score = best_score;
best_rows.nMethods   = sum(~isnan(cand_row),2);

% dt-specific validity: a method can give a good KL but an unrealistic dt
cand_row_dt = cand_row;
for i = 1:nExp
    for m = 1:nCand
        r = cand_row(i,m);
        if isnan(r), continue, end
        Tm = method_results.(candidate_methods{m});
        ok_dt = isfinite(Tm.dtD(r)) && isfinite(Tm.d_dtD(r)) && ...
                Tm.dtD(r) >= dtD_valid_min && Tm.dtD(r) <= dtD_valid_max;
        if ~ok_dt, cand_row_dt(i,m) = NaN; end
    end
end
best_rows.nMethods_dt = sum(~isnan(cand_row_dt),2);
best_rows.dtValid     = isfinite(best_rows.dtD) & ...
    best_rows.dtD >= dtD_valid_min & best_rows.dtD <= dtD_valid_max;

% method-to-method uncertainty (std across valid methods)
best_rows = addMethodSpread(best_rows, method_results, candidate_methods, cand_row, ...
    {'KL_SI','KL_cm2min','Pe_upump_L_KL','Pe_uMFM_L_KL'});
best_rows = addMethodSpread(best_rows, method_results, candidate_methods, cand_row_dt, ...
    {'dt_SI','dt_min','dtD'});

% total uncertainty = sqrt(fit error^2 + method spread^2)
fit_err_pairs = {'KL_SI','dKL_SI'; 'KL_cm2min','dKL_cm2min'; ...
                 'dt_SI','d_dt_SI'; 'dt_min','d_dt_min'; 'dtD','d_dtD'; ...
                 'Pe_upump_L_KL','dPe_upump_L_KL'; 'Pe_uMFM_L_KL','dPe_uMFM_L_KL'};
best_rows = addTotalUncert(best_rows, fit_err_pairs);

% register as pseudo-method
method_results.best_per_key = best_rows;
best_method = "best_per_key";
best_method_table = best_rows;

% print
disp(table(filedataExp.Key, best_rows.model, ...
    best_rows.KL_cm2min, best_rows.dKL_cm2min, best_rows.uncertKL_cm2min, best_rows.totUncertKL_cm2min, ...
    best_rows.dt_min, best_rows.d_dt_min, best_rows.uncertDt_min, best_rows.totUncertDt_min, ...
    best_rows.dtD, best_rows.d_dtD, best_rows.uncertDtD, best_rows.totUncertDtD, ...
    best_rows.dtD_group_wdt, best_rows.d_dtD_group_wdt, best_rows.dtD_group_nwdt, best_rows.d_dtD_group_nwdt, ...
    best_rows.R2, best_rows.RMSE, best_rows.nMethods, best_rows.nMethods_dt, best_rows.dtValid, ...
    'VariableNames', {'Key','BestMethod', ...
    'KL_cm2min','dKL_cm2min','uncertKL_cm2min','totUncertKL_cm2min', ...
    'dt_min','d_dt_min','uncertDt_min','totUncertDt_min', ...
    'dtD','d_dtD','uncertDtD','totUncertDtD', ...
    'dtD_group_wdt','d_dtD_group_wdt','dtD_group_nwdt','d_dtD_group_nwdt', ...
    'R2','RMSE','nMethods','nMethods_dt','dtValid'}))

% store in expProcData
for i = 1:nExp
    key = filedataExp.Key(i);
    expProcData.(key).results = best_rows(i,:);
    expProcData.(key).BT.C_fit_best = 100 * best_rows.C_fit{i};
end

%% Plotting KL results
% Fitting and experimental data all CF plot all methods

colors = parula(length(method_names));

for i = 1:length(filedataExp.Key)
    figure
    t = expProcData.(filedataExp.Key(i)).BT.TimeElapsed;
    switch fitData
