%% Local functions
function name = uncertName(var)
    var  = char(var);
    name = ['uncert' upper(var(1)) var(2:end)];     % KL_SI -> uncertKL_SI
end

function name = totName(var)
    u    = uncertName(var);
    name = ['tot' upper(u(1)) u(2:end)];             % KL_SI -> totUncertKL_SI
end

function Tbest = addMethodSpread(Tbest, method_results, candidate_methods, cand_row, vars)
% Std of each variable across all valid candidate methods, per key.
    for v = 1:numel(vars)
        var   = vars{v};
        uname = uncertName(var);
        Tbest.(uname) = nan(height(Tbest),1);
        found = false;
        for i = 1:height(Tbest)
            vals = [];
            for m = 1:numel(candidate_methods)
                r = cand_row(i,m);
                if isnan(r), continue, end
                Tm = method_results.(candidate_methods{m});
                if ~ismember(var, Tm.Properties.VariableNames) || r > height(Tm), continue, end
                found = true;
                x = Tm.(var)(r);
                if isfinite(x), vals(end+1) = x; end 
            end
            if numel(vals) >= 2
                Tbest.(uname)(i) = std(vals);
            end
        end
        if ~found
            warning("addMethodSpread: column '%s' not found in method tables", var)
        end
    end
end

function T = addTotalUncert(T, pairs)
% pairs: {value var, fit-error var; ...}
% adds totUncert<Var> = sqrt(fitError^2 + methodSpread^2)
    for p = 1:size(pairs,1)
        var = pairs{p,1};  dvar = pairs{p,2};
        uname = uncertName(var);
        if ~all(ismember({dvar, uname}, T.Properties.VariableNames))
            warning("addTotalUncert: missing '%s' or '%s'", dvar, uname)
            continue
        end
        methErr = T.(uname);
        methErr(isnan(methErr)) = 0;     % <2 valid methods -> fit error only
        T.(totName(var)) = sqrt(T.(dvar).^2 + methErr.^2);
    end
end

function [Pe, dPe] = peAlpha(u, du, a, da, D0, dD0)
    Pe  = u.*a./D0;
    dPe = Pe.*sqrt((du./u).^2 + (da./a).^2 + (dD0./D0).^2);
end

function out = pooledAlphaFit(X, KL_SI, dKL_SI, alpha0_cm, min_pts_tau, beta)
% Pooled fit over experiments with different D0 and L.
% X = [Pe_upump_L_D0, D0_SI, L_SI]. Alpha fitted in cm (better scaling).
    sc = 60e4;                               % m2/s -> cm2/min
    y  = KL_SI*sc;
    w  = 1./(dKL_SI*sc).^2;  w = w/mean(w);
    nP = size(X,1);

    out = struct('alpha_cm',NaN,'d_alpha_cm',NaN,'R2_alpha',NaN, ...
                 'alpha_tau_cm',NaN,'d_alpha_tau_cm',NaN,'tau',NaN,'d_tau',NaN, ...
                 'R2_alpha_tau',NaN);

    % alpha only: p = alpha/L for each experiment (same convention as grouped fits)
    f1 = @(b,X) sc*arrayfun(@(k) KL_Pe_alpha_only_model(X(k,1), X(k,2), ...
                (b(1)/100)/X(k,3)), (1:size(X,1))');
    try
        [b,~,~,CovB] = nlinfit(X, y, f1, alpha0_cm, 'Weights', w);
        out.alpha_cm   = b(1);
        out.d_alpha_cm = sqrt(CovB(1,1));
        out.R2_alpha   = weightedR2(y, f1(b,X), w);
    catch ME
        warning("pooledAlpha:tauFitFailed", ...
            "pooled alpha+tau fit failed [%s]: %s", ME.identifier, ME.message)
    end

    % alpha + tau
    if nP >= min_pts_tau
        f2 = @(b,X) sc*arrayfun(@(k) KL_Pe_alpha_tau_model(X(k,1), X(k,2), ...
            [(b(1)/100)/X(k,3); b(2)], beta), (1:size(X,1))');
        a0 = out.alpha_cm;
        if ~isfinite(a0) || a0 <= 0, a0 = alpha0_cm; end
        try
            [b,~,~,CovB] = nlinfit(X, y, f2, [a0, 1.5], 'Weights', w);
            if b(2) > 0                       % keep only physical tortuosity
                out.alpha_tau_cm   = b(1);
                out.d_alpha_tau_cm = sqrt(CovB(1,1));
                out.tau            = b(2);
                out.d_tau          = sqrt(CovB(2,2));
                out.R2_alpha_tau   = weightedR2(y, f2(b,X), w);
            end
        catch ME
            warning("pooledAlpha:tauFitFailed", ...
                "pooled alpha+tau fit failed [%s]: %s", ME.identifier, ME.message)
        end
    end
end

function R2 = weightedR2(y, yhat, w)
    ybar = sum(w.*y)/sum(w);
    R2   = 1 - sum(w.*(y-yhat).^2) / sum(w.*(y-ybar).^2);
end

function lbl = pointLabels(Tg)
% "Q = x ml/min, run n (method)" for each row of a case table
    n = height(Tg);
    lbl = strings(n,1);
    hasRun = ismember('Run', Tg.Properties.VariableNames);
    for r = 1:n
        if hasRun
            runN = Tg.Run(r);
        else
            runN = sum(Tg.Q_mlmin(1:r) == Tg.Q_mlmin(r));   % repeat count of same Q
        end
        lbl(r) = "Q = " + Tg.Q_mlmin(r) + " ml/min, run " + runN + " (" + Tg.model(r) + ")";
    end
end

function row = setFixedDt(row, dtD, d_dtD, u, L)
% dt of a dt-fixed fit: value and uncertainty come from the setup group
    row.dtD      = dtD;
    row.d_dtD    = d_dtD;
    row.dt_SI    = dtD*L/u;
    row.d_dt_SI  = d_dtD*L/u;
    row.dt_min   = row.dt_SI/60;
    row.d_dt_min = row.d_dt_SI/60;
    % line volume/length uncertainties follow dt
    row.dL_lines     = row.v_lines_SI*row.d_dt_SI;
    row.d_L_lines_cm = row.dL_lines*100;
    row.dV_lines_cc  = row.Q_mlmin*row.d_dt_SI/60;
    row.d_V_lines_SI = row.dV_lines_cc*1e-6;
end