%% main_Validation.m
% Author: Ianna Gomez Mendez
%
% PURPOSE
%   Validate the methodology used to estimate binary-mixture molar
%   composition from:
%
%       - Corrected Coriolis density measurements
%       - MFM temperature measurements
%       - EOS to convert density to composition
%
%   The workflow evaluates the accuracy of converting measured density
%   into fluid composition and compares estimated compositions against
%   independently known reference compositions.
%
% -------------------------------------------------------------------------
% VALIDATION OBJECTIVE
% -------------------------------------------------------------------------
%
%   For binary mixtures:
%
%       Fluid1 + Fluid2
%
%   determine whether:
%
%       Density --> Composition
%
%   can be estimated accurately using:
%
%       1. Density calibration
%       2. Peng-Robinson EOS or NIST REFPROP
%       3. Density-composition interpolation
%
% -------------------------------------------------------------------------
% INPUTS
% -------------------------------------------------------------------------
%
% Experimental metadata:
%
%       input_val_H2CO2_260303.xlsx
%
% Thermodynamic-property databases:
%
%       input_PR_pure.xlsx
%       input_PR_BIP.xlsx
%
% Calibration results generated by main_Cal.m:
%
%       fittingRhoResultsAll.mat
%       nlfittingRhoResultsAll.mat
%       cal_curve_params.mat
%
% Experimental acquisition files:
%
%       Pumps (.dat)
%       Pressure transducers (.csv)
%       Mass flow meters (.csv)
%       PGD1 (.csv)
%       PGD2 (.csv)
%
% -------------------------------------------------------------------------
% WORKFLOW
% -------------------------------------------------------------------------
%
%   1. Import validation-experiment metadata.
%
%   2. Import raw acquisition files.
%
%   3. Synchronize timestamps and trim datasets using:
%
%          Pressure
%          Flow rate
%
%      operating conditions.
%
%   4. Group measurements according to pressure levels.
%
%   5. Apply the nonlinear MFM density-calibration model:
%
%          rho_MFM --> rho_corrected
%
%   6. Compute uncertainty bounds on corrected density.
%
%   7. Generate Peng-Robinson EOS or NIST REFPROP density surfaces:
%
%          rho(T,P,x)
%
%      for the experimental fluid pair.
%
%   8. Create interpolation functions:
%
%          x = f(T,rho)
%
%   9. Estimate fluid composition:
%
%          Ci
%
%      from measured:
%
%          rho_corrected
%          T_MFM
%
%  10. Estimate uncertainty:
%
%          dCi
%
%      using density-calibration uncertainty limits.
%
%  11. Compare:
%
%          Ci_ref
%          Ci_est
%
%      and fit a validation model.
%
%  12. Generate validation plots and statistics.
%
% -------------------------------------------------------------------------
% DENSITY CORRECTION
% -------------------------------------------------------------------------
%
%   Raw MFM density measurements are corrected using the linear 
%   calibration model or nonlinear calibration model obtained from:
%
%       main_Cal.m
% 
%   if linear:
%   All region: rho_corr =(rho_MFM - p1)/p2
%
%   if non-linear:
%   Low-density region:
%
%       rho_corr =
%           (rho_MFM - p1)/p2
%
%   High-density region:
%
%       rho_corr =
%           (rho_MFM - p1 + p3*p4)/(p2 + p3)
%
%   where:
%
%       p1, p2, p3, p4
%
%   are calibration parameters obtained from the density-calibration
%   workflow.
%
% -------------------------------------------------------------------------
% COMPOSITION ESTIMATION
% -------------------------------------------------------------------------
%
%   For each pressure level:
%
%       1. Generate Peng-Robinson EOS or NIST REFPROP densities on a grid:
%
%              T
%              x
%
%       2. Create:
%
%              x = f(T,rho)
%
%          interpolation surfaces.
%
%       3. Estimate composition from:
%
%              rho_corr
%
%       4. Estimate uncertainty using:
%
%              rho_corrMin
%              rho_corrMax
%
% -------------------------------------------------------------------------
% VALIDATION METRICS
% -------------------------------------------------------------------------
%
%   Estimated composition:
%
%       Ci
%
%   Reference composition:
%
%       Ci_ref
%
%   A linear model is fitted:
%
%       Ci_est = n + m*Ci_ref
%
%   and the following metrics are reported:
%
%       RMSE
%       R²
%       Intercept (n)
%       Slope (m)
%
% -------------------------------------------------------------------------
% GENERATED VARIABLES
% -------------------------------------------------------------------------
%
%   BT contains:
%
%       TimeStamp
%
%       rho_MFM
%       rho_corr
%       rho_corrMin
%       rho_corrMax
%
%       T_MFM
%       q_MFM
%
%       Ci_ref
%       Ci
%       CiMin
%       CiMax
%       dC
%
% -------------------------------------------------------------------------
% OUTPUTS
% -------------------------------------------------------------------------
%
% MATLAB files:
%
%       expRawData.mat
%       expTrimData.mat
%       expProcData.mat
%       Cval_lin_params.mat
%       CvalFitResults.mat
%
% Excel files:
%
%       *_Raw.xlsx
%       *_Trim.xlsx
%       CvalFitResults.xlsx
%
% Figures:
%
%       Val-P1500.png
%
% -------------------------------------------------------------------------
% VALIDATION RESULT
% -------------------------------------------------------------------------
%
%   The final validation curve quantifies agreement between:
%
%       C_H2,ref
%
%   and
%
%       C_H2,estimated
%
%   across the investigated pressure, temperature, and composition
%   ranges.
%
%   The resulting RMSE provides an estimate of the expected uncertainty
%   associated with density-based composition measurements.
%
% -------------------------------------------------------------------------
% DEPENDENCIES
% -------------------------------------------------------------------------
%
% Import functions:
%
%       import_inputCal
%       import_pumps_data
%       import_trans_data
%       import_MFM_data
%       import_PGD1_data
%       import_PGD2_data
%
% Calibration workflow:
%
%       main_Cal.m
%
% Thermodynamic calculations:
%
%       densZ_PR
%       calc_BIP
%       calc_ai_bi
%       getMixtureProps_REFPROP
%
% Utility functions:
%
%       trim_time_P_Q
%
% -------------------------------------------------------------------------
% NOTES
% -------------------------------------------------------------------------
%
%   - Assumes binary-mixture systems.
%
%   - Assumes Peng-Robinson EOS or NIST REFPROP adequately describes mixture densities.
%
%   - Composition error is strongly influenced by density-calibration
%     uncertainty, which is better if using NIST REFPROP
%
%   - Intended as a validation workflow for density-derived composition
%     estimates before applying the methodology to breakthrough-curve
%     experiments.

